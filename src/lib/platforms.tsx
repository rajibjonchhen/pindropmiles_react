/** Work out which platform a URL belongs to. */
export function detect(url: string): PlatformKey {
  if (/^mailto:/i.test(url || "")) return "mail";
  try {
    const host = new URL(url).hostname.replace(/^www\./, "");
    for (const key of Object.keys(PLATFORMS) as PlatformKey[]) {
      if (PLATFORMS[key].h.some((x) => host === x || host.endsWith("." + x))) return key;
    }
  } catch {
    /* not a valid URL */
  }
  return "web";
}

/** Only allow http(s), mailto and tel links. */
export const safe = (url: string) => (/^(https?:|mailto:|tel:)/i.test(url || "") ? url : "#");

/** Extract a YouTube video id (watch, youtu.be, shorts, embed, live). */
export function ytId(url: string): string | null {
  const m = (url || "").match(
    /(?:youtu\.be\/|youtube\.com\/(?:watch\?(?:.*&)?v=|shorts\/|embed\/|live\/))([\w-]{11})/
  );
  return m ? m[1] : null;
}

